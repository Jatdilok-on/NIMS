const I18nContext = createContext<I18nContextValue | null>(null);

function isSupportedLang(val: unknown): val is LanguageCode {
  return val === 'th' || val === 'en' || val === 'zh' || val === 'ja';
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<LanguageCode>('th');

  const applyLang = useCallback((nextLang: LanguageCode) => {
    setLangState(nextLang);
    if (typeof document !== 'undefined') {
      document.documentElement.lang = nextLang;
    }
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('nims_lang', nextLang);
    }
  }, []);

  useEffect(() => {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('nims_lang');
      if (isSupportedLang(saved)) {
        applyLang(saved);
        return;
      }
    }
    applyLang('th');
  }, [applyLang]);

  const t = useCallback(
    (key: TranslationKey): string => {
      return DICTIONARY[lang][key] ?? DICTIONARY.en[key] ?? key;
    },
    [lang],
  );

  return (
    <I18nContext.Provider value={{ lang, setLang: applyLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
